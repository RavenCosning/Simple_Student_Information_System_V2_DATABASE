    private void btnSearchStudentActionPerformed(java.awt.event.ActionEvent evt) {                                                 
        String studentId = txtStudentID.getText().trim();
        String firstName = txtFirstName.getText().trim();
        String lastName = txtLastName.getText().trim();
        String programCode = (cmbProgram.getSelectedItem() == null)
                ? "" : cmbProgram.getSelectedItem().toString().trim();
        String yearLevel = (cmbYearLevel.getSelectedItem() == null)
                ? "" : cmbYearLevel.getSelectedItem().toString().trim();
        String gender = (cmbGender.getSelectedItem() == null)
                ? "" : cmbGender.getSelectedItem().toString().trim();

        if (programCode.equalsIgnoreCase("all")) {
            programCode = "";
        }
        if (yearLevel.equalsIgnoreCase("all")) {
            yearLevel = "";
        }
        if (gender.equalsIgnoreCase("all")) {
            gender = "";
        }

        boolean hasSearchInput = !studentId.isEmpty() || !firstName.isEmpty()
                || !lastName.isEmpty() || !programCode.isEmpty()
                || !yearLevel.isEmpty() || !gender.isEmpty();

        if (!hasSearchInput) {
            warn("Enter at least one search criterion.", "No Search Criteria");
            return;
        }

        List<Student> results = studentDAO.searchAll(studentId, firstName, lastName,
                programCode, yearLevel, gender);

        if (results.isEmpty()) {
            info("No matching student record found.", "No Results");
            return;
        }

        // Load ALL results into table
        studentTableModel.setRowCount(0);
        for (Student s : results) {
            studentTableModel.addRow(new Object[]{
                s.getId(), s.getFirstName(), s.getLastName(),
                s.getProgramCode(), s.getYear(), s.getGender()
            });
        }

        lblStudentCount.setText("Search Results: " + results.size());
        lblStudentPage.setText("Search Mode");
        btnStudentPrev.setEnabled(false);
        btnStudentNext.setEnabled(false);
        isSearchMode = true;

    }                                                


