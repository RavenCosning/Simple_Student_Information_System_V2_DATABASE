    private void loadStudentTable() {
        studentTableModel.setRowCount(0);
        int offset = (studentCurrentPage - 1) * studentRowsPerPage;
        List<Student> students = studentDAO.search("", "id", true, studentRowsPerPage, offset);
        for (Student s : students) {
            studentTableModel.addRow(new Object[]{s.getId(), s.getFirstName(), s.getLastName(), s.getProgramCode(), s.getYear(), s.getGender()});
        }
        studentTotalCount = studentDAO.count("");
        lblStudentCount.setText("Total Students: " + studentTotalCount);
        updateStudentPagination(studentTotalCount);
    }

    private void updateStudentPagination(int total) {
        int totalPages = (int) Math.ceil((double) total / studentRowsPerPage);
        if (totalPages == 0) {
            totalPages = 1;
        }
        lblStudentPage.setText("Page " + studentCurrentPage + " of " + totalPages);
        btnStudentPrev.setEnabled(studentCurrentPage > 1);
        btnStudentNext.setEnabled(studentCurrentPage < totalPages);
    }

