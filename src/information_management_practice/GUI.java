    private void btnUpdateStudentActionPerformed(java.awt.event.ActionEvent evt) {                                                 
        int viewRow = tblStudents.getSelectedRow();
        if (viewRow == -1) {
            warn("Please select a student record first.", "No Record Selected");
            return;
        }
        int modelRow = tblStudents.convertRowIndexToModel(viewRow);
        String originalId = studentTableModel.getValueAt(modelRow, 0).toString().trim();
        String id = txtStudentID.getText().trim();
        String firstName = toTitleCase(txtFirstName.getText().trim());
        String lastName = toTitleCase(txtLastName.getText().trim());
        Object progObj = cmbProgram.getSelectedItem();
        if (progObj == null) {
            warn("No programs available.", "Program Required");
            return;
        }
        String program = progObj.toString().trim();
        String yearLevel = cmbYearLevel.getSelectedItem().toString();
        String gender = cmbGender.getSelectedItem().toString();
        if (program.equalsIgnoreCase("All") || yearLevel.equalsIgnoreCase("All") || gender.equalsIgnoreCase("All")) {
            error("Please select a valid Program, Year Level, and Gender (not 'All').", "Invalid Selection");
            return;
        }
        if (id.isEmpty() || firstName.isEmpty() || lastName.isEmpty()) {
            warn("Please fill in all required fields.", "Missing Information");
            return;
        }
        if (!id.matches("\\d{4}-\\d{4}")) {
            error("Invalid Student ID format.\nRequired: YYYY-NNNN.", "Invalid Format");
            return;
        }
        int year = Integer.parseInt(id.substring(0, 4));
        int currentYear = java.time.Year.now().getValue();
        if (year < 2015 || year > currentYear) {
            error("Student year must be between 2015 and " + currentYear + ".", "Invalid Year");
            return;
        }
        if (!firstName.matches("[a-zA-Z\\-' ]+")) {
            error("First name contains invalid characters.", "Invalid Format");
            return;
        }
        if (!lastName.matches("[a-zA-Z\\-' ]+")) {
            error("Last name contains invalid characters.", "Invalid Format");
            return;
        }
        if (!originalId.equalsIgnoreCase(id) && studentDAO.exists(id)) {
            warn("Student ID \"" + id + "\" already exists.", "Duplicate ID");
            return;
        }
        if (!confirm("Save changes to Student ID " + originalId + "?", "Confirm Update")) {
            return;
        }
        boolean success = studentDAO.updateStudent(originalId, new Student(id, firstName, lastName, program, Integer.parseInt(yearLevel), gender));
        if (!success) {
            error("Failed to update student.", "Database Error");
            return;
        }
        info("Student updated successfully.", "Success");
        loadStudentTable();
        btnClearStudent.doClick();
        selectRowByCode(tblStudents, studentTableModel, id, 0);
    }                                                

